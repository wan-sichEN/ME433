import matplotlib.pyplot as plt
import numpy as np

import csv

t_A = [] # column 1
dataA = [] # column 2

with open('sigA.csv') as f:
    # open the csv file
    reader = csv.reader(f)
    for row in reader:
        # read the rows 1 one by one
        t_A.append(float(row[0])) # leftmost column
        dataA.append(float(row[1])) # second column

Fs = 1/(t_A[1] - t_A[0]) # sample rate (10 kHz)
y = dataA
n = len(y) # length of the signal
k = np.arange(n) 
T = n/Fs
frq = k/T # two sides frequency range
frq = frq[range(int(n/2))] # one side frequency range
Y = np.fft.fft(y)/n # fft computing and normalization
Y = Y[range(int(n/2))]

# MAF
maf_data = []
X = 75
for i in range(n):
    avg = 0
    for j in range(X):
        if i-j >= 0: # treats earlier X values as zeros
            avg += dataA[i-j]
    avg = avg/X
    maf_data.append(avg)

Y_maf = np.fft.fft(maf_data)/n # fft computing and normalization
Y_maf = Y_maf[range(int(n/2))]

# Comparing unfiltered and MAF
fig, (ax1, ax2) = plt.subplots(2, 1)

ax1.plot(t_A,y,'k')
ax1.plot(t_A, maf_data, 'r')
ax1.set_xlabel('Time')
ax1.set_ylabel('Amplitude')

ax2.loglog(frq,abs(Y),'k') # plotting the fft
ax2.loglog(frq, abs(Y_maf), 'r')
ax2.set_xlabel('Freq (Hz)')
ax2.set_ylabel('|Y(freq)|')

ax1.legend(['Original', 'MAF'])
ax2.legend(['Original', 'MAF'])
fig.suptitle(f"Signal A MAF: {X} Data Points Averaged")
plt.show()

#IIR
iir_data = [0]*n
iir_data[0] = dataA[0]

A = .96
B = 1 - A
for i in range(1,n):
    iir_data[i] = A*iir_data[i-1] + B*dataA[i]

Y_iir = np.fft.fft(iir_data)/n # fft computing and normalization
Y_iir = Y_iir[range(int(n/2))]

# Comparing unfiltered and IIR
fig, (ax1, ax2) = plt.subplots(2, 1)

ax1.plot(t_A,y,'k')
